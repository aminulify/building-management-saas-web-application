/**
 * Invoice PDF drawn in the browser with jsPDF (loaded only when "Download" is clicked). English labels and "BDT":
 * the built-in PDF fonts have no Bengali glyphs, so Bengali text is replaced with "?" instead of broken boxes.
 */
import type { InvoiceData } from "./types";

type RGB = [number, number, number];
const NAVY: RGB = [15, 23, 42];
const GREY: RGB = [100, 116, 139];
const BRAND: RGB = [123, 47, 247];
const GREEN: RGB = [22, 163, 74];

const safe = (s: string | null | undefined) => (s ?? "").replace(/[^\u0000-ÿ]/g, "?");
const money = (v: string | number) => `BDT ${new Intl.NumberFormat("en-US", { minimumFractionDigits: Number(v) % 1 ? 2 : 0, maximumFractionDigits: 2 }).format(Number(v))}`;
const day = (iso: string | null | undefined) => (iso ? new Intl.DateTimeFormat("en-GB", { dateStyle: "medium", timeZone: "Asia/Dhaka" }).format(new Date(iso)) : "-");
const CYCLE = { MONTHLY: "Monthly", QUARTERLY: "Quarterly (4 months)", YEARLY: "Yearly" } as const;

async function logo(): Promise<{ data: string; w: number; h: number } | null> {
  try {
    const res = await fetch("/images/amaderghor-logo-EN.png");
    if (!res.ok) return null;
    const blob = await res.blob();
    const data = await new Promise<string>((ok, no) => { const r = new FileReader(); r.onload = () => ok(String(r.result)); r.onerror = no; r.readAsDataURL(blob); });
    return { data, w: 543, h: 95 };
  } catch { return null; }
}

/** Draws the invoice and starts the download. Returns the file name. */
export async function downloadInvoicePdf(inv: InvoiceData): Promise<string> {
  const [{ jsPDF }, { autoTable }, lg] = await Promise.all([import("jspdf"), import("jspdf-autotable"), logo()]);
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const W = doc.internal.pageSize.getWidth();
  const M = 48;

  if (lg) doc.addImage(lg.data, "PNG", M, 36, (lg.w / lg.h) * 32, 32);
  else doc.setFont("helvetica", "bold").setFontSize(20).setTextColor(...BRAND).text("AmaderGhor", M, 60);
  doc.setFont("helvetica", "bold").setFontSize(22).setTextColor(...NAVY).text("INVOICE", W - M, 56, { align: "right" });
  doc.setFont("helvetica", "normal").setFontSize(10).setTextColor(...GREY).text(inv.number, W - M, 72, { align: "right" });
  doc.setDrawColor(226, 232, 240).line(M, 90, W - M, 90);

  doc.setFont("helvetica", "bold").setFontSize(9).setTextColor(...GREY).text("BILLED TO", M, 112).text("DETAILS", W / 2 + 10, 112);
  doc.setFont("helvetica", "normal").setFontSize(11).setTextColor(...NAVY);
  const who = [safe(inv.customer.fullName), `@${safe(inv.customer.username)}`, inv.customer.ownerCode ? `Owner ID: ${inv.customer.ownerCode}` : "", safe(inv.customer.phone), safe(inv.customer.email)].filter(Boolean);
  who.forEach((l, i) => doc.text(l, M, 130 + i * 15));
  const details = [`Issued: ${day(inv.issuedAt)}`, `Paid via: ${inv.payment.gateway === "MANUAL_BKASH" ? "bKash Send Money" : safe(inv.payment.gateway)}`, `TrxID: ${safe(inv.payment.reference) || "-"}`, `Verified: ${day(inv.payment.verifiedAt)}`];
  details.forEach((l, i) => doc.text(l, W / 2 + 10, 130 + i * 15));

  autoTable(doc, {
    startY: 230, margin: { left: M, right: M },
    head: [["Description", "Period", "Amount"]],
    body: [[
      `AmaderGhor ${safe(inv.plan.nameEn ?? inv.plan.code ?? "plan")} plan${inv.cycle ? ` (${CYCLE[inv.cycle]})` : ""}`,
      inv.periodStart && inv.periodEnd ? `${day(inv.periodStart)} - ${day(inv.periodEnd)}` : "-",
      money(inv.amount),
    ]],
    styles: { font: "helvetica", fontSize: 10, cellPadding: 8, textColor: NAVY },
    headStyles: { fillColor: BRAND, textColor: [255, 255, 255] },
    columnStyles: { 2: { halign: "right" } },
  });
  const y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 24;
  doc.setFont("helvetica", "bold").setFontSize(12).setTextColor(...NAVY).text("Total paid", W - M - 140, y).text(money(Number(inv.amount) - Number(inv.refunded)), W - M, y, { align: "right" });
  if (Number(inv.refunded) > 0) doc.setFont("helvetica", "normal").setFontSize(9).setTextColor(...GREY).text(`Includes a refund of ${money(inv.refunded)}`, W - M, y + 14, { align: "right" });
  doc.setFont("helvetica", "bold").setFontSize(11).setTextColor(...GREEN).text("PAID", M, y);
  doc.setFont("helvetica", "normal").setFontSize(8).setTextColor(...GREY).text("This invoice was generated by AmaderGhor after the payment was verified by our team.", M, doc.internal.pageSize.getHeight() - 36);

  const file = `${inv.number}.pdf`;
  doc.save(file);
  return file;
}
