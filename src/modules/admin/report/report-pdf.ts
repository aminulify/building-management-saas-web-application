/**
 * "Export Invoice": the sales invoice of the chosen dates, drawn in the browser with jsPDF (loaded only on click).
 * English labels and "BDT": the built-in PDF fonts have no Bengali glyphs.
 */
import type { ReportBreakdown } from "./types";

type RGB = [number, number, number];
const NAVY: RGB = [15, 23, 42];
const GREY: RGB = [100, 116, 139];
const BRAND: RGB = [10, 132, 240];
const GREEN: RGB = [22, 163, 74];

const safe = (s: string) => s.replace(/[^\u0000-ÿ]/g, "?");
const money = (v: string | number) => `BDT ${new Intl.NumberFormat("en-US", { minimumFractionDigits: Number(v) % 1 ? 2 : 0, maximumFractionDigits: 2 }).format(Number(v))}`;
const dayOf = (d: string) => new Intl.DateTimeFormat("en-GB", { dateStyle: "medium", timeZone: "UTC" }).format(new Date(`${d}T00:00:00Z`));
const stamp = (iso: string) => new Intl.DateTimeFormat("en-GB", { dateStyle: "medium", timeStyle: "short", timeZone: "Asia/Dhaka" }).format(new Date(iso));

async function logo(): Promise<{ data: string; w: number; h: number } | null> {
  try {
    const res = await fetch("/images/amaderghor-logo-EN.png");
    if (!res.ok) return null;
    const blob = await res.blob();
    const data = await new Promise<string>((ok, no) => { const r = new FileReader(); r.onload = () => ok(String(r.result)); r.onerror = no; r.readAsDataURL(blob); });
    return { data, w: 543, h: 95 };
  } catch { return null; }
}

/** Draws the invoice and starts the download. Returns the file name. */
export async function downloadReportInvoice(b: ReportBreakdown): Promise<string> {
  const [{ jsPDF }, { autoTable }, lg] = await Promise.all([import("jspdf"), import("jspdf-autotable"), logo()]);
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const W = doc.internal.pageSize.getWidth();
  const M = 48;
  const number = `AG-REPORT-${b.range.from.replaceAll("-", "")}-${b.range.to.replaceAll("-", "")}`;

  if (lg) doc.addImage(lg.data, "PNG", M, 36, (lg.w / lg.h) * 32, 32);
  else doc.setFont("helvetica", "bold").setFontSize(20).setTextColor(...BRAND).text("AmaderGhor", M, 60);
  doc.setFont("helvetica", "bold").setFontSize(22).setTextColor(...NAVY).text("SALES INVOICE", W - M, 56, { align: "right" });
  doc.setFont("helvetica", "normal").setFontSize(10).setTextColor(...GREY).text(number, W - M, 72, { align: "right" });
  doc.setDrawColor(226, 232, 240).line(M, 90, W - M, 90);

  doc.setFont("helvetica", "bold").setFontSize(9).setTextColor(...GREY).text("PERIOD", M, 112).text("DETAILS", W / 2 + 10, 112);
  doc.setFont("helvetica", "normal").setFontSize(11).setTextColor(...NAVY);
  doc.text(`${dayOf(b.range.from)} - ${dayOf(b.range.to)}`, M, 130);
  doc.text("Verified payments only", M, 145);
  doc.text(`Generated: ${stamp(b.generatedAt)}`, W / 2 + 10, 130);
  doc.text(`Items sold: ${b.totalSold}`, W / 2 + 10, 145);

  autoTable(doc, {
    startY: 180, margin: { left: M, right: M },
    head: [["Item", "Sold", "Sales"]],
    body: [
      ...b.plans.map((p) => [`${safe(p.nameEn)} plan`, String(p.sold), money(p.amount)]),
      ["Boosts", String(b.boost.sold), money(b.boost.amount)],
    ],
    styles: { font: "helvetica", fontSize: 10, cellPadding: 8, textColor: NAVY },
    headStyles: { fillColor: BRAND, textColor: [255, 255, 255] },
    columnStyles: { 1: { halign: "right" }, 2: { halign: "right" } },
  });
  const y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 24;
  doc.setFont("helvetica", "bold").setFontSize(12).setTextColor(...NAVY).text("Total sales", W - M - 150, y).text(money(b.total), W - M, y, { align: "right" });
  doc.setFont("helvetica", "bold").setFontSize(11).setTextColor(...GREEN).text("VERIFIED", M, y);
  doc.setFont("helvetica", "normal").setFontSize(8).setTextColor(...GREY).text("Generated by AmaderGhor from verified bKash payments. Pending, failed and refunded payments are not included.", M, doc.internal.pageSize.getHeight() - 36);

  const file = `${number}.pdf`;
  doc.save(file);
  return file;
}
